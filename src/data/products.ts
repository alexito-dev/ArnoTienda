export const getStoredProducts = (): Product[] => {
  try {
    const saved = localStorage.getItem('arno_custom_products');
    if (saved) {
      const parsed = JSON.parse(saved);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch {
    /* fallback to initial */
  }
  return INITIAL_PRODUCTS;
};

export const saveProductsToStorage = (products: Product[]) => {
  localStorage.setItem('arno_custom_products', JSON.stringify(products));
};

export const resetProductsToDefault = (): Product[] => {
  localStorage.removeItem('arno_custom_products');
  return INITIAL_PRODUCTS;
};

export const PRODUCTS: Product[] = getStoredProducts();

